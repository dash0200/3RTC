"""Generates the desktop icon set from the web app's icons (client-ts/src/components/icons.tsx).

Writes assets/icons/<name>.svg (stroke 2, the web default) and <name>-bold.svg (stroke 2.4), plus
src/icons.rs with the `Icon` enum. Run from desktop/crates/ui after icons.tsx changes:
    python tools/gen_icons.py
"""
import pathlib, re

HERE = pathlib.Path(__file__).resolve().parent.parent
SRC = HERE.parents[2] / 'client-ts' / 'src' / 'components' / 'icons.tsx'
OUT = HERE / 'assets' / 'icons'

text = SRC.read_text(encoding='utf-8')


def block(name):
    start = text.index(f'const {name}: Record<string, React.ReactNode> = {{')
    depth, i = 0, text.index('{', start + 30)
    for j in range(i, len(text)):
        if text[j] == '{':
            depth += 1
        elif text[j] == '}':
            depth -= 1
            if depth == 0:
                return text[i + 1:j]


def entries(body):
    out, i = [], 0
    for m in re.finditer(r'^\s{2}(\w+):\s*', body, re.M):
        out.append((m.group(1), m.end()))
    res = []
    for k, (name, pos) in enumerate(out):
        end = out[k + 1][1] - len(out[k + 1][0]) - 3 if k + 1 < len(out) else len(body)
        chunk = body[pos:end]
        res.append((name, ' '.join(re.findall(r'<(?:path|rect|circle|line|polyline)\b[^>]*/>', chunk))))
    return res


def jsx_to_svg(markup):
    markup = markup.replace('fill="currentColor"', 'fill="#fff"')
    return re.sub(r'(\b[a-z]+)([A-Z])([a-z]+)=', lambda m: f'{m.group(1)}-{m.group(2).lower()}{m.group(3)}=', markup)


def camel_to_pascal(n):
    return n[0].upper() + n[1:]


OUT.mkdir(parents=True, exist_ok=True)
names = []
for name, markup in entries(block('paths')):
    for suffix, width in (('', '2'), ('-bold', '2.4')):
        svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#fff" '
               f'stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round">{jsx_to_svg(markup)}</svg>\n')
        (OUT / f'{name}{suffix}.svg').write_text(svg, encoding='utf-8')
    names.append((name, True))
for name, markup in entries(block('filled')):
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="#fff">{jsx_to_svg(markup)}</svg>\n'
    (OUT / f'{name}.svg').write_text(svg, encoding='utf-8')
    names.append((name, False))

variants = '\n'.join(f'    /// `{n}` in the web set.\n    {camel_to_pascal(n)},' for n, _ in names)
paths = '\n'.join(f'            Self::{camel_to_pascal(n)} => ("icons/{n}.svg", {"Some(\"icons/" + n + "-bold.svg\")" if stroked else "None"}),' for n, stroked in names)
files = '\n'.join(
    f'    ("icons/{n}.svg", include_bytes!("../assets/icons/{n}.svg")),' + (f'\n    ("icons/{n}-bold.svg", include_bytes!("../assets/icons/{n}-bold.svg")),' if s else '')
    for n, s in names)
(HERE / 'src' / 'icons.rs').write_text(f'''//! The web app's icons (`client-ts/src/components/icons.tsx`). Generated by `tools/gen_icons.py`:
//! don't edit by hand.

/// An icon from the web app's set.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Icon {{
{variants}
}}

impl Icon {{
    /// Asset paths: the normal stroke, and the bold (2.4) one if it has strokes.
    pub(crate) const fn paths(self) -> (&'static str, Option<&'static str>) {{
        match self {{
{paths}
        }}
    }}
}}

/// The icon files, by path.
pub(crate) const FILES: &[(&str, &[u8])] = &[
{files}
];
''', encoding='utf-8')
print(len(names), 'icons')
